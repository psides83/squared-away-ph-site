import Link from "next/link";
import { HelpPanel } from "@/components/help-panel";
import { ConfirmButton } from "@/components/confirm-button";
import { configureAutomation } from "@/app/admin/invoices/recurring/actions";
import { dateLabel } from "@/lib/format";
export type AutomationConfig = {
  enabled: boolean;
  updated_at: string;
  last_checked_at: string | null;
};
export type AutomationRun = {
  id: string;
  business_date: string;
  started_at: string;
  finished_at: string | null;
  state: string;
  reason: string | null;
  results: {
    stay_id: string;
    invoice_id?: string;
    state: string;
    reason?: string | null;
  }[];
};
const timestamp = (value: string) =>
  new Intl.DateTimeFormat("en-US", {
    dateStyle: "medium",
    timeStyle: "short",
    timeZone: "America/Chicago",
  }).format(new Date(value));
const labels: Record<string, string> = {
  complete: "Completed",
  review: "Needs review",
  error: "Failed or partly failed",
  blocked: "Access needs review",
  running: "Running",
  issued: "Finalized",
};
export function BillingAutomation({
  config,
  runs,
  ready,
}: {
  config: AutomationConfig | null;
  runs: AutomationRun[];
  ready: boolean;
}) {
  if (!config)
    return (
      <p className="notice error">
        Automatic billing settings could not load. Check the latest migration.
      </p>
    );
  const stale =
    config.enabled &&
    (!config.last_checked_at ||
      Date.now() - Date.parse(config.last_checked_at) > 36 * 60 * 60 * 1000);
  return (
    <div className="stack">
      <section className="panel">
        <div className="panel-heading">
          <h2>Daily automatic billing</h2>
          <span className="tag">{config.enabled ? "Enabled" : "Off"}</span>
        </div>
        <div className="record-form stack">
          <p>
            Checks enabled training agreements daily in the morning, Central
            time. Complete invoices finalize automatically. Incomplete records
            and missing actual-cost approvals leave drafts for review.
          </p>
          {!ready && (
            <p className="notice">
              Deployment setup is incomplete. Automatic billing needs the server
              credentials and production environment described in the deployment
              guide before it can run.
            </p>
          )}
          <p className="muted">
            Last scheduler check:{" "}
            {config.last_checked_at
              ? `${timestamp(config.last_checked_at)} Central`
              : "No check recorded yet"}
            .{" "}
            {config.enabled
              ? "Enabled does not confirm that the scheduler has run; check this timestamp and the history below."
              : "No invoices will be generated by the scheduler while this is off."}
          </p>
          {stale && (
            <p className="notice error">
              No scheduler check has been recorded in the last 36 hours. Review
              the deployment schedule before relying on automatic billing. You
              can still prepare due cycles manually.
            </p>
          )}
          <form action={configureAutomation}>
            <input
              type="hidden"
              name="enabled"
              value={config.enabled ? "false" : "true"}
            />
            {config.enabled || ready ? (
              <ConfirmButton
                className={config.enabled ? "button secondary" : "button"}
                message={
                  config.enabled
                    ? "Turn off future automatic runs? Existing invoices and drafts are kept."
                    : "Enable daily automatic billing for recurring agreements? Complete cycles will finalize without another confirmation. Actual-cost periods still require your readiness approval."
                }
              >
                {config.enabled
                  ? "Turn off automatic billing"
                  : "Enable automatic billing"}
              </ConfirmButton>
            ) : null}
          </form>
        </div>
      </section>
      <HelpPanel title="How daily billing works">
        <p>
          Only agreements with recurring billing enabled participate. Each daily
          run processes at most one due cycle per agreement, up to 25
          agreements. Earlier periods come first. Review drafts are retried on
          later days; voided cycles require your decision. A cycle that needs
          review blocks later cycles for that agreement.
        </p>
        <p>
          The same business date is processed once. Fixing records after today’s
          run can be followed by manual preparation, or will be picked up on a
          later daily run. Payments and invoice delivery are separate; no emails
          are sent.
        </p>
        <p>
          Production scheduling must be configured before enabling this feature.
          The administrator enabling billing authorizes scheduled operations;
          removing their administrator access blocks future runs until another
          administrator re-enables billing.
        </p>
      </HelpPanel>
      <section className="panel">
        <div className="panel-heading">
          <h2>Recent daily runs</h2>
          <span className="count-badge">Latest 20</span>
        </div>
        {!runs.length ? (
          <p>No automatic runs recorded yet.</p>
        ) : (
          runs.map((run) => (
            <details key={run.id}>
              <summary>
                {dateLabel(run.business_date)} ·{" "}
                {labels[run.state] ?? run.state} · {run.results.length}{" "}
                agreements
              </summary>
              <p className="muted">
                Started {timestamp(run.started_at)} Central
                {run.finished_at
                  ? ` · Finished ${timestamp(run.finished_at)} Central`
                  : ""}
              </p>
              {run.reason && <p className="notice error">{run.reason}</p>}
              <div className="stack">
                {run.results.map((result, index) => (
                  <div key={`${result.stay_id}-${index}`}>
                    <p>
                      <strong>{labels[result.state] ?? result.state}</strong>
                      {result.reason ? ` · ${result.reason}` : ""}
                    </p>
                    <div className="row-actions">
                      <Link
                        className="text-link"
                        href={`/admin/training/${result.stay_id}`}
                      >
                        Training agreement
                      </Link>
                      {result.invoice_id && (
                        <Link
                          className="text-link"
                          href={`/admin/invoices/${result.invoice_id}`}
                        >
                          Review invoice
                        </Link>
                      )}
                    </div>
                  </div>
                ))}
              </div>
            </details>
          ))
        )}
      </section>
    </div>
  );
}
